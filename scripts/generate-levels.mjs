/**
 * Regenerates the built-in level data from the deterministic seeds in
 * src/levels/levelConfigs.js:
 *   - src/levels/seedLevels.json (bundled with the app, works offline)
 *   - supabase/seed.sql          (inserts the same levels into Supabase)
 *
 * Usage: npm run levels:generate
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LEVEL_CONFIGS } from '../src/levels/levelConfigs.js';
import { generateLevel } from '../src/engine/generator.js';
import { validateLevel } from '../src/levels/validator.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const levels = LEVEL_CONFIGS.map((config) => {
  const level = generateLevel(config);
  const result = validateLevel(level);
  if (!result.valid) {
    console.error(`Level ${config.number} failed validation:`, result.errors);
    process.exit(1);
  }
  const sizes = level.solution.map((s) => s.cells.length);
  const monos = sizes.filter((n) => n === 1).length;
  console.log(
    `Level ${String(level.number).padStart(2)} ${level.difficulty.padEnd(12)} ${level.width}x${level.height} ` +
      `pieces ${level.totalPieces}/${level.requiredPieces}  sizes [${sizes.sort((a, b) => b - a).join(',')}]  singles ${monos}`,
  );
  return level;
});

writeFileSync(resolve(root, 'src/levels/seedLevels.json'), JSON.stringify(levels) + '\n');

const sqlString = (value) => `'${String(value).replace(/'/g, "''")}'`;
const rows = levels.map(
  (l) =>
    `  (${sqlString(l.id)}, ${l.number}, ${l.version}, ${sqlString(l.difficulty)}, ${l.width}, ${l.height}, ` +
    `${l.totalPieces}, ${l.requiredPieces}, ${l.timeLimit ?? 'null'}, ${l.hints}, ${l.seed}, ` +
    `${sqlString(JSON.stringify(l.pieces))}::jsonb, ${sqlString(JSON.stringify(l.solution))}::jsonb, ${l.published})`,
);

const sql = `-- Generated by scripts/generate-levels.mjs. Do not edit by hand.
insert into public.levels
  (id, number, version, difficulty, width, height, total_pieces, required_pieces, time_limit, hints, seed, pieces, solution, published)
values
${rows.join(',\n')}
on conflict (id) do update set
  number = excluded.number,
  version = excluded.version,
  difficulty = excluded.difficulty,
  width = excluded.width,
  height = excluded.height,
  total_pieces = excluded.total_pieces,
  required_pieces = excluded.required_pieces,
  time_limit = excluded.time_limit,
  hints = excluded.hints,
  seed = excluded.seed,
  pieces = excluded.pieces,
  solution = excluded.solution,
  published = excluded.published;
`;

mkdirSync(resolve(root, 'supabase'), { recursive: true });
writeFileSync(resolve(root, 'supabase/seed.sql'), sql);
console.log(`\nWrote ${levels.length} levels to src/levels/seedLevels.json and supabase/seed.sql`);
